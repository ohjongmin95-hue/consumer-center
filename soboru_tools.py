def install(S):
    app = S.app

    @app.route('/tools')
    def tools():
        return render_template('soboru_tools.html', groups=CALC_GROUPS, calcs=CALCS, n_words=len(DICT), samples=LAW_SAMPLES)

    @app.route('/tools/calc')
    def calc_home():
        return redirect(url_for('tools') + '#calc')

    @app.route('/tools/calc/<slug>')
    def calc(slug):
        c = CALC.get(slug)
        if not c: abort(404)
        more = [x for x in CALCS if x['group'] == c['group'] and x['slug'] != slug][:4]
        return render_template('soboru_calc.html', c=c, more=more)

    @app.route('/tools/dict')
    def dictionary():
        a = request.args
        cat = a.get('c', ''); cat = cat if cat in DICT_CATS else ''
        cho = a.get('k', ''); cho = cho if cho in CHO_LIST else ''
        q = a.get('q', '')
        return render_template('soboru_dict.html', rows=dict_rows(q, cat, cho), q=' '.join(q.split())[:30], cat=cat, cho=cho, cats=DICT_CATS, chos=CHO_LIST, total=len(DICT))

    @app.route('/tools/law')
    def law_find():
        q = ' '.join(request.args.get('q', '').split())[:60]
        rows, laws = [], []
        rag = app.extensions.get('lawrag') or {}
        rc = rag.get('corpus')
        if rc is not None:
            try:
                laws = sorted(rc.laws(), key=lambda l: l['name'])
                if len(q) >= 2:
                    pick = request.args.get('law', '')
                    keys = [l['key'] for l in laws if l['key'] == pick] or None
                    for h in rc.search(q, 15, keys):
                        if h['match'] < 0.2: continue
                        key, art = h['ref'].split(':', 1)
                        rows.append({'label': h['label'], 'law': h['law'], 'art': art, 'title': h['title'], 'text': rc.clip(h['text'], 600), 'source': h['source']})
            except Exception as e:   # 법령 모음을 못 읽어도 화면은 뜨게 (국가법령정보센터 링크는 남음)
                S.app.logger.warning('법령 찾기 실패: %s', str(e)[:160])
        return render_template('soboru_law.html', q=q, rows=rows, laws=[l for l in laws if l['key'] not in ('easylaw',) and not l['key'].startswith('appx')],
                               pick=request.args.get('law', ''), samples=LAW_SAMPLES)

