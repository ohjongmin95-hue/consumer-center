CHO = 'ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ'
CHO_MAIN = {'ㄲ': 'ㄱ', 'ㄸ': 'ㄷ', 'ㅃ': 'ㅂ', 'ㅆ': 'ㅅ', 'ㅉ': 'ㅈ'}
CHO_LIST = ['ㄱ', 'ㄴ', 'ㄷ', 'ㄹ', 'ㅁ', 'ㅂ', 'ㅅ', 'ㅇ', 'ㅈ', 'ㅊ', 'ㅋ', 'ㅌ', 'ㅍ', 'ㅎ', 'A']


def initial(word):
    c = (word or ' ')[0]
    if '가' <= c <= '힣': ch = CHO[(ord(c) - 0xAC00) // 588]; return CHO_MAIN.get(ch, ch)
    return 'A'


def dict_rows(q='', cat='', cho=''):
    q = ' '.join((q or '').split())[:30]
    rows = [{'word': w, 'cat': c, 'text': t, 'cho': initial(w), 'id': 'w' + str(i)} for i, (w, c, t) in enumerate(DICT)]
    if cat: rows = [r for r in rows if r['cat'] == cat]
    if cho: rows = [r for r in rows if r['cho'] == cho]
    if q:
        k = q.replace(' ', '').lower()
        rows = sorted([r for r in rows if k in (r['word'] + r['text']).replace(' ', '').lower()], key=lambda r: k not in r['word'].replace(' ', '').lower())
    else: rows.sort(key=lambda r: (r['cho'] == 'A', r['word']))
    return rows


