def cite(ref):
    """'ecom:제17조:①:1' 같은 참조를 조문 원문 묶음으로 바꾼다. 항·호는 없어도 된다."""
    key,art,*rest=ref.split(':')
    para=rest[0] if rest else None;item=rest[1] if len(rest)>1 else None
    law=TEXTS[key];a=law['articles'][art]
    paras=[p for p in a['paras'] if para is None or p['n']==para]
    if item:paras=[dict(p,items=[i for i in p['items'] if i['n']==item]) for p in paras]
    label=f"{SHORT[key]} {art}"+(f" 제{'①②③④⑤⑥⑦⑧⑨⑩⑪'.index(para)+1}항" if para else '')+(f" 제{item}호" if item else '')
    return {'ref':ref,'label':label,'title':a['title'],'paras':paras,'law':law['name'],'kind':law['kind'],'no':law['no'],'effective':law['effective'],'source':law['source']}

def sources():
    return [{'short':SHORT[k],'name':v['name'],'kind':v['kind'],'no':v['no'],'effective':v['effective'],'source':v['source']} for k,v in TEXTS.items()]

def plain(ref):
    """조문을 한 덩어리 글로 (답변 초안의 근거로 넘길 때)."""
    c=cite(ref);out=[]
    for p in c['paras']:
        out.append(((p['n']+' ') if p['n'] else '')+p['text'])
        for i in p['items']:
            out.append(f"  {i['n']}. {i['text']}")
            for s in i.get('subs',[]):out.append(f"    {s['n']}. {s['text']}")
    return c['label']+' ('+c['title']+')\n'+'\n'.join(out)

